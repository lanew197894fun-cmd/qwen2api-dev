// 過濾目錄（不改這些）
const SKIP_DIRS = new Set(["node_modules", ".git", ".bak", "dist", ".cache"]);

const SKIP_PREFIXES = ["node_modules", ".git"];

function convertText(text) {
  let result = "";
  for (const ch of text) {
    result += S2T_MAP.get(ch) || ch;
  }
  return result;
}

function shouldSkip(dir) {
  const base = path.basename(dir);
  const rel = path.relative(".", dir);
  if (SKIP_DIRS.has(base)) return true;
  for (const p of SKIP_PREFIXES) {
    if (rel.startsWith(p)) return true;
  }
  return false;
}

function isTargetFile(name) {
  return name.endsWith(".md") || name.endsWith(".wiki");
}

function collectFiles(root) {
  const files = [];
  const stat = fs.statSync(root);
  if (stat.isFile()) {
    if (isTargetFile(root)) files.push(root);
    return files;
  }
  const entries = fs.readdirSync(root, { withFileTypes: true });
  for (const e of entries) {
    const fp = path.join(root, e.name);
    if (e.isDirectory()) {
      if (!shouldSkip(fp)) files.push(...collectFiles(fp));
    } else if (isTargetFile(e.name)) {
      files.push(fp);
    }
  }
  return files;
}

function hasSimplified(text) {
  for (const ch of text) {
    if (S2T_MAP.has(ch)) return true;
  }
  return false;
}

function countSimplified(text) {
  let count = 0;
  for (const ch of text) {
    if (S2T_MAP.has(ch)) count++;
  }
  return count;
}

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const checkOnly = args.includes("--check");
const noBackup = args.includes("--no-backup");
const target = args.find((a) => !a.startsWith("--")) || ".";

if (!fs.existsSync(target)) {
  console.error(`❌ 路徑不存在: ${target}`);
  process.exit(1);
}

const files = collectFiles(target);
console.log(`📂 掃描 ${files.length} 個 .md/.wiki 檔案...\n`);

let totalFixed = 0;
let totalSimp = 0;

for (const fp of files) {
  let content;
  try {
    content = fs.readFileSync(fp, "utf-8");
  } catch {
    continue;
  }

  const simpCount = countSimplified(content);
  if (simpCount === 0) continue;

  totalSimp += simpCount;
  totalFixed++;
  const rel = path.relative(".", fp);

  if (checkOnly) {
    console.log(`  📄 ${rel} (${simpCount} 個簡體字)`);
    continue;
  }

  const converted = convertText(content);
  if (converted === content) continue;

  if (dryRun) {
    console.log(`  🔄 ${rel} — ${simpCount} 個簡體字 → 繁體（預覽）`);
    continue;
  }

  // 備份
  if (!noBackup) {
    const bak = fp + ".bak";
    if (!fs.existsSync(bak)) {
      fs.writeFileSync(bak, content, "utf-8");
    }
  }

  fs.writeFileSync(fp, converted, "utf-8");
  console.log(`  ✅ ${rel} — ${simpCount} 個簡體字已轉換`);
}

console.log(`\n━━━━━━━━━━━━━━━━━━━━━━━━━━`);

if (checkOnly) {
  console.log(`📊 共 ${totalFixed} 個檔案含簡體中文，${totalSimp} 處待轉換`);
  if (totalFixed > 0) {
    console.log(`💡 執行轉換: bun traditionalize.js ${target}`);
  }
} else if (dryRun) {
  console.log(`📊 預覽: ${totalFixed} 個檔案將被轉換，${totalSimp} 處簡體字`);
  console.log(`💡 確認執行（移除 --dry-run）: bun traditionalize.js ${target}`);
} else {
  if (noBackup) {
    console.log(`✅ 已完成: ${totalFixed} 個檔案已轉換，${totalSimp} 處簡體字`);
  } else {
    console.log(
      `✅ 已完成: ${totalFixed} 個檔案已轉換，${totalSimp} 處簡體字（備份: .bak）`,
    );
  }
}
